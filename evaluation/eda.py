"""Exploratory data analysis of MC-OCR -> docs/dataset_eda.md.

Every number in the report is computed here from the local data; re-run after
any change to the adapter or splits::

    python -m evaluation.eda
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import Counter
from pathlib import Path

from PIL import Image

from ai.normalization.text import fold_for_match
from ai.schemas import FIELD_NAMES
from evaluation.dataset_adapter import DEFAULT_ROOT, McocrRecord, load_mcocr
from evaluation.splits import MIN_STRATUM_SIZE, SPLITS_DIR, anonymize_strata, seller_strata

OUT = Path("docs/dataset_eda.md")


def pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}%" if d else "-"


def q(values: list[float], p: float) -> float:
    s = sorted(values)
    return s[min(len(s) - 1, int(round(p * (len(s) - 1))))] if s else float("nan")


def table(header: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def field_presence(records: list[McocrRecord]) -> dict[str, int]:
    return {f: sum(1 for r in records if r.regions_of(f)) for f in FIELD_NAMES}


def build_report(root: Path, splits_dir: Path) -> str:
    recs = load_mcocr(root)
    n = len(recs)
    summary = json.loads((splits_dir / "summary.json").read_text(encoding="utf-8"))
    split_ids = {
        s: {
            it["img_id"]
            for it in json.loads((splits_dir / f"{s}.json").read_text("utf-8"))["items"]
        }
        for s in ("train", "dev", "test")
    }
    out: list[str] = []
    w = out.append

    w("# MC-OCR 2021 — Dataset EDA\n")
    w(
        "> Generated by `python -m evaluation.eda` from the local copy of the data. "
        "Do not edit by hand; re-run instead.\n"
    )

    # ------------------------------------------------------------------ overview
    w("## 1. Overview\n")
    w(
        table(
            ["Item", "Value"],
            [
                ["Labelled images (`mcocr_train_df.csv` + `train_images/`)", n],
                [
                    "Unlabelled public validation images (`val_images/`)",
                    summary["num_unlabelled_val"],
                ],
                ["CSV SHA-256", f"`{summary['source_csv_sha256'][:16]}…`"],
                ["Annotated regions", sum(len(r.regions) for r in recs)],
                [
                    "Regions / image (mean · median · max)",
                    f"{statistics.mean(len(r.regions) for r in recs):.2f} · "
                    f"{statistics.median(len(r.regions) for r in recs):.0f} · "
                    f"{max(len(r.regions) for r in recs)}",
                ],
            ],
        )
    )
    w(
        "\nThe `val_images/` have no ground truth: they are **not** used for any metric. "
        "Internal train/dev/test splits are carved out of the 1,155 labelled images.\n"
    )

    # ------------------------------------------------------------------ images
    w("## 2. Images\n")
    sizes = Counter((r.width, r.height) for r in recs)
    portrait = sum(1 for r in recs if r.height > r.width)
    file_kb = [r.image_path.stat().st_size / 1024 for r in recs]
    size_mismatch = 0
    for r in recs:
        with Image.open(r.image_path) as im:
            size_mismatch += im.size != (r.width, r.height)
    w(
        table(
            ["Item", "Value"],
            [
                ["Distinct resolutions", len(sizes)],
                ["Portrait / landscape", f"{portrait} / {n - portrait}"],
                [
                    "Width min–max (px)",
                    f"{min(r.width for r in recs)}–{max(r.width for r in recs)}",
                ],
                [
                    "Height min–max (px)",
                    f"{min(r.height for r in recs)}–{max(r.height for r in recs)}",
                ],
                [
                    "File size median · p95 (KB)",
                    f"{statistics.median(file_kb):.0f} · {q(file_kb, 0.95):.0f}",
                ],
                ["Annotation width/height ≠ real image size", size_mismatch],
            ],
        )
    )
    w("\nMost common resolutions:\n")
    w(
        table(
            ["W×H", "Images", "Share"],
            [[f"{a}×{b}", c, pct(c, n)] for (a, b), c in sizes.most_common(6)],
        )
    )
    w("")

    # ------------------------------------------------------------------ quality
    w("## 3. Official image-quality score (IQA, 0–1)\n")
    qs = [r.quality for r in recs]
    w(
        f"mean {statistics.mean(qs):.3f} · std {statistics.pstdev(qs):.3f} · "
        f"min {min(qs):.3f} · p25 {q(qs, 0.25):.3f} · median {statistics.median(qs):.3f} · "
        f"p75 {q(qs, 0.75):.3f} · max {max(qs):.3f}\n"
    )
    bins = Counter(min(int(x * 10), 9) for x in qs)
    w(
        table(
            ["Score bin", "Images", "Share"],
            [
                [f"{b / 10:.1f}–{(b + 1) / 10:.1f}", bins[b], pct(bins[b], n)]
                for b in range(10)
                if bins[b]
            ],
        )
    )
    w(
        "\nThe score is the share of text lines annotators judged *clear*. It is the official "
        "Task-1 label; any blur/OK classifier built later must be evaluated against it, "
        "not against a self-chosen threshold.\n"
    )

    # ------------------------------------------------------------------ fields
    w("## 4. Key-information fields\n")
    pres = field_presence(recs)
    rows = []
    for f in FIELD_NAMES:
        per_img = [len(r.regions_of(f)) for r in recs if r.regions_of(f)]
        lens = [len(getattr(r.gt.raw_fields, f) or "") for r in recs if getattr(r.gt.raw_fields, f)]
        dist = Counter(min(k, 3) for k in per_img)
        rows.append(
            [
                f"`{f}`",
                f"{pres[f]} ({pct(pres[f], n)})",
                n - pres[f],
                f"{dist[1]} / {dist[2]} / {dist[3]}",
                f"{statistics.median(lens):.0f} · {q(lens, 0.95):.0f} · {max(lens)}"
                if lens
                else "-",
            ]
        )
    w(
        table(
            [
                "Field",
                "Images with field",
                "Missing",
                "Images with 1 / 2 / ≥3 regions",
                "Raw text chars median · p95 · max",
            ],
            rows,
        )
    )
    all4 = sum(1 for r in recs if all(r.regions_of(f) for f in FIELD_NAMES))
    w(
        f"\nImages with all four fields: **{all4} ({pct(all4, n)})**. "
        "A missing field is represented as `null` and is a valid target, not an error.\n"
    )

    w("Region multiplicity matters for evaluation:\n")
    w("- `seller_address` is often split over several lines → joined in reading order.")
    w(
        '- `total_cost` usually has **2 regions**: the keyword ("Tổng tiền:") and the amount. '
        "Only the amount is the value."
    )
    w("- `timestamp` is sometimes split into date and time regions.\n")

    # ------------------------------------------------------------------ normalization
    w("## 5. Ground-truth normalization outcome\n")
    ts_present = [r for r in recs if r.gt.raw_fields.timestamp]
    ts_full = sum(1 for r in ts_present if r.gt.fields.timestamp and "T" in r.gt.fields.timestamp)
    ts_date = sum(
        1 for r in ts_present if r.gt.fields.timestamp and "T" not in r.gt.fields.timestamp
    )
    tc_present = [r for r in recs if r.regions_of("total_cost")]
    tc_ok = sum(1 for r in tc_present if r.gt.fields.total_cost is not None)
    w(
        table(
            ["Field", "Annotated", "Normalized", "Breakdown"],
            [
                [
                    "timestamp",
                    len(ts_present),
                    f"{ts_full + ts_date} ({pct(ts_full + ts_date, len(ts_present))})",
                    f"date+time {ts_full}, date only {ts_date}, "
                    f"null {len(ts_present) - ts_full - ts_date}",
                ],
                [
                    "total_cost",
                    len(tc_present),
                    f"{tc_ok} ({pct(tc_ok, len(tc_present))})",
                    f"null {len(tc_present) - tc_ok} "
                    "(keyword-only region, ambiguous or mislabelled)",
                ],
            ],
        )
    )
    w("")
    issues = Counter(i.split(":")[0] for r in recs for i in r.issues)
    w("Data-quality flags raised by the adapter (an image can have several):\n")
    explain = {
        "missing_seller": "no SELLER region",
        "missing_seller_address": "no ADDRESS region",
        "missing_timestamp": "no TIMESTAMP region",
        "missing_total_cost": "no TOTAL_COST region",
        "total_cost_no_amount": "TOTAL_COST regions hold only a keyword (amount not annotated)",
        "timestamp_no_time": "date without time",
        "timestamp_unparsed": (
            "text present but no valid date (typos like `2C20`, `20199`, garbage)"
        ),
        "timestamp_time_only": "only a clock time, no date",
        "timestamp_multiple_times": "check-in/check-out style; first time is used",
        "suspect_timestamp_contains_total": "TIMESTAMP region holds an amount (label swap)",
        "suspect_total_cost_contains_date": "TOTAL_COST region holds a date (label swap)",
        "total_cost_ambiguous": "several different amounts with equal support → null",
        "total_cost_multiple_values": "several amounts, majority value used",
        "no_annotations": "row with zero regions",
        "label_category_mismatch": "label string disagrees with category id (`TOTAL_TOTAL_COST`)",
        "length_mismatch": "texts/labels/polygons counts differ",
    }
    w(
        table(
            ["Flag", "Images", "Meaning"],
            [[f"`{k}`", v, explain.get(k, "")] for k, v in issues.most_common()],
        )
    )
    clean = sum(
        1
        for r in recs
        if not any(
            i.startswith(("suspect_", "total_cost_ambiguous", "label_category", "no_annotations"))
            for i in r.issues
        )
    )
    w(
        f"\nImages without any *suspect/ambiguous* flag: **{clean} ({pct(clean, n)})** — "
        "evaluation reports metrics on all images and on this clean subset.\n"
    )
    w(
        "Per-field scoring set for normalized metrics (see `evaluation/data_contract.md`): "
        "a field whose annotation exists but cannot be normalized is *unscorable* — it is "
        "neither counted right nor wrong.\n"
    )
    rows = []
    for f in FIELD_NAMES:
        scorable = [r for r in recs if f not in r.unscorable_fields()]
        with_value = sum(1 for r in scorable if getattr(r.gt.fields, f) is not None)
        rows.append(
            [f"`{f}`", len(scorable), with_value, len(scorable) - with_value, n - len(scorable)]
        )
    w(
        table(
            ["Field", "Scorable images", "Target = value", "Target = null (absent)", "Unscorable"],
            rows,
        )
    )
    w("")

    # ------------------------------------------------------------------ sellers
    w("## 6. Sellers (store chains)\n")
    sellers = Counter(fold_for_match(r.gt.fields.seller) for r in recs if r.gt.fields.seller)
    top3 = sum(c for _, c in sellers.most_common(3))
    w(
        f"{len(sellers)} distinct seller strings (after case/punctuation folding). "
        f"The top 3 cover **{top3} images ({pct(top3, n)})** — the dataset is dominated by a few "
        "chains, so a random split would let template-specific rules look better than they are.\n"
    )
    w(
        table(
            ["Seller (folded)", "Images", "Share"],
            [[s, c, pct(c, n)] for s, c in sellers.most_common(10)],
        )
    )
    w(
        "\nSeller strings also contain annotation/OCR variants of the same chain "
        "(e.g. `VitCommerce`), which is why strata use a frequency threshold rather than "
        "trying to canonicalise names.\n"
    )

    # ------------------------------------------------------------------ duplicates
    w("## 7. Duplicates and leakage control\n")
    g = summary["groups"]
    w(
        table(
            ["Item", "Value"],
            [
                ["Duplicate groups (≥2 labelled images)", g["num_multi_image_groups"]],
                ["Labelled images inside such groups", g["images_in_multi_image_groups"]],
                ["Largest group", g["largest_group"]],
                [
                    "Linking pairs: identical bytes (SHA-256)",
                    g["linking_pairs_by_signal"]["sha256"],
                ],
                [
                    "Linking pairs: near-duplicate photo (dHash)",
                    g["linking_pairs_by_signal"]["dhash"],
                ],
                [
                    "Linking pairs: same transaction re-photographed",
                    g["linking_pairs_by_signal"]["transaction"],
                ],
                [
                    "Labelled images that also appear in `val_images/`",
                    len(summary["train_images_duplicated_in_val"]),
                ],
            ],
        )
    )
    w(
        "\n**dHash calibration.** A 64-bit dHash (8×8) is useless on this data: different "
        "receipts of the same chain collide at 1–2 bits because every photo is a white strip "
        "on a similar background. With a 1024-bit dHash (32×32), re-encoded/screenshotted "
        "copies of one photo were 78 and 110 bits apart, while the closest pair of *different* "
        "receipts from one store was 223 bits apart; the threshold is set to 150. Receipts "
        "photographed twice from a different angle are not caught by any global hash "
        "(≈500 bits apart) — they are caught by the transaction key "
        "(seller + timestamp to the minute + total), verified visually.\n"
    )

    # ------------------------------------------------------------------ splits
    w("## 8. Internal splits\n")
    w(
        f"Seed `{summary['seed']}`, ratios {summary['ratios']}, grouped by duplicate group, "
        "stratified by seller (sellers with < 15 images → `other`). Manifests: "
        "`data/splits/{train,dev,test,smoke}.json`.\n"
    )
    by_id = {r.img_id: r for r in recs}
    rows = []
    for s, ids in split_ids.items():
        rs = [by_id[i] for i in ids]
        p = field_presence(rs)
        rows.append(
            [s, len(rs), f"{statistics.mean(r.quality for r in rs):.3f}"]
            + [pct(p[f], len(rs)) for f in FIELD_NAMES]
        )
    w(table(["Split", "Images", "Mean IQA"] + [f"has `{f}`" for f in FIELD_NAMES], rows))
    w(
        "\nImages per stratum (manifests store only the anonymous id; the seller name is "
        "resolved from the local data when this report is generated):\n"
    )
    _, stratum_name = anonymize_strata(seller_strata(recs, MIN_STRATUM_SIZE))
    w(
        table(
            ["Stratum", "Seller (folded)", "train", "dev", "test"],
            [
                [s, stratum_name.get(s, "—"), v["train"], v["dev"], v["test"]]
                for s, v in summary["strata"].items()
            ],
        )
    )
    overlap = (
        (split_ids["train"] & split_ids["dev"])
        | (split_ids["train"] & split_ids["test"])
        | (split_ids["dev"] & split_ids["test"])
    )
    w(
        f"\nImage overlap between splits: **{len(overlap)}**. "
        "Duplicate groups crossing splits: **0** by construction (checked in tests).\n"
    )

    w("## 9. Implications for the next phases\n")
    w("- OCR/KIE must expect missing fields (~6–7% per field) and output `null`.")
    w(
        "- `total_cost` extraction must pick the *amount* next to a total keyword, not the "
        "keyword and not item counts (`TẠI QUẦY 03`)."
    )
    w(
        "- Timestamp parsing must handle many separators (`/ - . :`), `CH/SA` (PM/AM), "
        "time-before-date, and check-in/out pairs."
    )
    w("- Report metrics on all images **and** on the clean subset; label noise caps EM.")
    w(
        "- A few chains dominate: report per-stratum metrics so a rule tuned for VinCommerce "
        "does not hide failures on the long tail."
    )
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    ap.add_argument("--splits", type=Path, default=SPLITS_DIR)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build_report(args.root, args.splits), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
