"""Image-quality (IQA) benchmark against the official MC-OCR score.

Fits on *train*, reports on *dev* (or test once, at the end):

* ``mean``        — always predict the train mean (the bar to beat);
* ``image``       — ridge on image statistics only (no OCR needed);
* ``ocr``         — ridge on OCR-derived features only;
* ``image+ocr``   — both (the model saved to ``configs/quality_model.json``).

Metrics: MAE, RMSE, Pearson r, Spearman ρ; and, for the advisory "poor image"
warning (GT score < 0.5), precision/recall at a threshold chosen on train.

CLI::

    python -m evaluation.iqa_eval fit --ocr-run v6_medium@gpu0
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from ai.preprocessing.image import load_image
from ai.quality.assess import (
    IMAGE_FEATURES,
    MODEL_PATH,
    OCR_FEATURES,
    LinearQualityModel,
    image_features,
    ocr_features,
)
from evaluation.dataset_adapter import load_split
from evaluation.ocr_eval import load_results

REPORT = Path("evaluation/reports/iqa_dev.md")
POOR_GT = 0.5


def features_for(split: str, ocr_run: str) -> tuple[list[str], np.ndarray, dict]:
    records = load_split(split)
    ocr = load_results(split, ocr_run)
    ids, ys, feats = [], [], []
    for r in records:
        if r.img_id not in ocr:
            continue
        im = load_image(r.image_path)
        f = image_features(im) | ocr_features(ocr[r.img_id], im)
        ids.append(r.img_id)
        ys.append(r.quality)
        feats.append(f)
    return ids, np.array(ys), {k: np.array([f[k] for f in feats]) for k in feats[0]}


def _rank(a: np.ndarray) -> np.ndarray:
    return np.argsort(np.argsort(a)).astype(float)


def metrics(y: np.ndarray, p: np.ndarray) -> dict:
    out = {"mae": float(np.abs(y - p).mean()), "rmse": float(np.sqrt(((y - p) ** 2).mean()))}
    if p.std() > 0:
        out["pearson"] = float(np.corrcoef(y, p)[0, 1])
        out["spearman"] = float(np.corrcoef(_rank(y), _rank(p))[0, 1])
    else:
        out["pearson"] = out["spearman"] = float("nan")
    return out


def best_threshold(y: np.ndarray, p: np.ndarray) -> float:
    """Threshold on predictions maximising F1 for detecting GT < POOR_GT."""
    pos = y < POOR_GT
    best, best_f1 = POOR_GT, -1.0
    for t in np.linspace(0.3, 0.75, 46):
        pred = p < t
        tp = (pred & pos).sum()
        prec = tp / pred.sum() if pred.sum() else 0
        rec = tp / pos.sum() if pos.sum() else 0
        f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0
        if f1 > best_f1:
            best, best_f1 = float(t), f1
    return best


def detection(y: np.ndarray, p: np.ndarray, t: float) -> dict:
    pos, pred = y < POOR_GT, p < t
    tp = int((pred & pos).sum())
    return {
        "threshold": round(t, 3),
        "positives": int(pos.sum()),
        "flagged": int(pred.sum()),
        "precision": tp / pred.sum() if pred.sum() else float("nan"),
        "recall": tp / pos.sum() if pos.sum() else float("nan"),
    }


def fit_and_report(ocr_run: str, eval_split: str = "dev") -> Path:
    _, y_tr, F_tr = features_for("train", ocr_run)
    _, y_ev, F_ev = features_for(eval_split, ocr_run)
    groups = {
        "image": IMAGE_FEATURES,
        "ocr": OCR_FEATURES,
        "image+ocr": IMAGE_FEATURES + OCR_FEATURES,
    }
    rows, saved = [], None
    base = np.full_like(y_ev, y_tr.mean())
    rows.append(("mean (baseline)", metrics(y_ev, base), None))
    for name, feats in groups.items():
        Xtr = np.stack([F_tr[f] for f in feats], 1)
        Xev = np.stack([F_ev[f] for f in feats], 1)
        model = LinearQualityModel.fit(
            Xtr, y_tr, feats, alpha=1.0, trained_on=f"train ({len(y_tr)} images), OCR {ocr_run}"
        )
        t = best_threshold(y_tr, model.predict(Xtr))
        model.poor_threshold = t
        p = model.predict(Xev)
        rows.append((name, metrics(y_ev, p), detection(y_ev, p, t)))
        if name == "image+ocr":
            saved = model

    MODEL_PATH.parent.mkdir(parents=True, exist_ok=True)
    MODEL_PATH.write_text(saved.model_dump_json(indent=2), encoding="utf-8")

    corr = sorted(
        ((f, float(np.corrcoef(F_tr[f], y_tr)[0, 1])) for f in IMAGE_FEATURES + OCR_FEATURES),
        key=lambda x: -abs(x[1]),
    )
    lines = [
        f"# Image quality (IQA) — fit on train, evaluated on `{eval_split}`\n",
        "> Generated by `python -m evaluation.iqa_eval fit`. Target: official MC-OCR "
        "`anno_image_quality` (share of clearly readable text lines, 0–1).\n",
        f"Train images: {len(y_tr)} · {eval_split} images: {len(y_ev)} · OCR run: `{ocr_run}` · "
        f"{eval_split} GT mean {y_ev.mean():.3f}, std {y_ev.std():.3f}\n",
        "| Model | MAE | RMSE | Pearson r | Spearman ρ "
        "| Poor-image precision | Poor-image recall |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, m, d in rows:
        pr = f"{d['precision']:.0%}" if d else "-"
        rc = f"{d['recall']:.0%}" if d else "-"
        lines.append(
            f"| {name} | {m['mae']:.3f} | {m['rmse']:.3f} | {m['pearson']:.2f} | "
            f"{m['spearman']:.2f} | {pr} | {rc} |"
        )
    d = rows[-1][2]
    lines += [
        "",
        f"Poor image = GT score < {POOR_GT} ({d['positives']} of {len(y_ev)} {eval_split} images). "
        f"Threshold on the prediction chosen on train: {d['threshold']}; flagged {d['flagged']}.",
        "",
        "Correlation of each feature with the GT score on train:",
        "",
        "| Feature | r |",
        "|---|---:|",
    ] + [f"| `{f}` | {r:+.2f} |" for f, r in corr]
    lines += ["", f"Saved model: `{MODEL_PATH}` (`image+ocr`)."]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return REPORT


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fit")
    f.add_argument("--ocr-run", default="v6_medium@gpu0")
    f.add_argument("--eval-split", default="dev")
    args = ap.parse_args()
    print(fit_and_report(args.ocr_run, args.eval_split))
    print(json.dumps(json.loads(MODEL_PATH.read_text())["coef"][:3]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
